def _db_ssl_pem_from_env() -> str:
    # For production, prioritize env variables (supports full
    # cert chain)
    env_cert = normalize_db_ssl_pem_raw(
        os.environ.get('DB_SSL_CERT') or os.environ.get('capem') or ''
    )
    if env_cert:
        return env_cert
    # Fall back to ca.pem file for local development
    # (avoids issues with escaped newlines in .env)
    ca_pem_file = os.path.join(BASE_DIR, 'ca.pem')
    if os.path.exists(ca_pem_file):
        with open(ca_pem_file, 'r') as f:
            content = f.read().strip()
            # Handle escaped newlines in the file
            if '\\n' in content:
                content = content.replace('\\n', '\n')
            return content
    return ''


def _apply_db_ssl_cert(db_config, db_ssl_cert_content, ca_pem_path):
    # sslmode/sslrootcert are Postgres-only OPTIONS — a local
    # DATABASE_URL=sqlite:///... alongside a ca.pem must not crash.
    if not db_ssl_cert_content or 'postgres' not in db_config.get(
        'ENGINE', ''
    ):
        return
    pem_content = format_db_ssl_pem(db_ssl_cert_content)
    with open(ca_pem_path, 'w') as f:
        f.write(pem_content)
    db_config.setdefault('OPTIONS', {})
    db_config['OPTIONS']['sslmode'] = 'require'
    db_config['OPTIONS']['sslrootcert'] = ca_pem_path


